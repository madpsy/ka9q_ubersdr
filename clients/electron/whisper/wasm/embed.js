// embed.js — the last step of ../build.sh --only=wasm, on the host: put the
// module where the v2 page serves it, and tell the page what it is.
//
//   node embed.js <whisper.cpp commit> <emsdk image>
//
// Writes:
//   static/v2/whisper/whisper-stt.js, whisper-stt.wasm
//       served at /v2/whisper/, loaded by the speech-to-text worker. Committed:
//       building them needs Docker and emscripten, and the server's own build
//       needs neither.
//   static/v2/src/extensions/whisper/wasm/build.generated.js
//       what the page bundles about them: a version for the URL, so a browser
//       never pairs a cached module with new glue, and the pins of the models
//       the browser offers, from ../models.json.
//
// static/v2/test/whisperwasm.test.js holds the generated file to the sources
// and to models.json, so a change to either that was not rebuilt fails there.
'use strict';
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const HERE = path.resolve(__dirname, '..');
const REPO = path.resolve(HERE, '../../..');
const V2 = path.join(REPO, 'static', 'v2');
const [commit, image] = process.argv.slice(2);
if (!commit || !image) {
    console.error('usage: node embed.js <whisper.cpp commit> <emsdk image>');
    process.exit(2);
}

const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

// What the module is built from, in this order; whisperwasm.test.js has the
// same list. The whisper.cpp commit and the toolchain go in too.
const SOURCES = [
    'whisper_core.h', 'whisper_core.cpp', 'whisper_session.h', 'whisper_session.cpp',
    'wasm/whisper_wasm.cpp', 'wasm/CMakeLists.txt',
];
const h = crypto.createHash('sha256');
for (const f of SOURCES) h.update(f + '\0').update(fs.readFileSync(path.join(HERE, f))).update('\0');
h.update(commit + '\0' + image);
const sourceSha256 = h.digest('hex');

const outDir = path.join(V2, 'whisper');
fs.mkdirSync(outDir, { recursive: true });
const files = {};
for (const f of ['whisper-stt.js', 'whisper-stt.wasm']) {
    const buf = fs.readFileSync(path.join(HERE, 'build', 'wasm', f));
    fs.writeFileSync(path.join(outDir, f), buf);
    files[f] = { size: buf.length, sha256: sha256(buf) };
}
const version = sha256(Buffer.from(files['whisper-stt.js'].sha256 + files['whisper-stt.wasm'].sha256)).slice(0, 16);

const pins = {};
const all = JSON.parse(fs.readFileSync(path.join(HERE, 'models.json'), 'utf8'));
for (const [id, v] of Object.entries(all)) {
    if (id.startsWith('//') || !Array.isArray(v.clients) || !v.clients.includes('browser')) continue;
    pins[id] = { file: v.file, url: v.url, size: v.size, sha256: v.sha256 };
}

const out = `// GENERATED by clients/electron/whisper/build.sh --only=wasm (wasm/embed.js).
// Do not edit: change the sources there and run that. See ../engines/wasm.js.

// The module served from /v2/whisper/: \`version\` goes on its URL.
export const WASM_BUILD = ${JSON.stringify({
    version,
    sourceSha256,
    whisperCpp: commit,
    emsdk: image,
    files,
}, null, 4)};

// models.json's entries for the browser, pinned by URL, size and SHA-256.
export const WASM_PINS = ${JSON.stringify(pins, null, 4)};
`;
fs.writeFileSync(path.join(V2, 'src', 'extensions', 'whisper', 'wasm', 'build.generated.js'), out);
console.log(`  static/v2/whisper/whisper-stt.wasm  ${(files['whisper-stt.wasm'].size / 1e6).toFixed(2)} MB, version ${version}`);

#!/usr/bin/env bash
# build.sh — build the audio classifier's WebAssembly module for the v2 page.
#
# Writes two files, both committed, as the browser's Whisper is
# (static/v2/whisper/):
#
#   static/v2/audioclass/audioclass.wasm    this package, GOOS=js GOARCH=wasm
#   static/v2/src/lib/audioClass/wasm_exec.js   Go's loader for it
#
# The two must come from the same Go: wasm_exec.js is the other half of the
# module's runtime, and a pair from different releases fails at start-up. So
# the loader is copied from the GOROOT that built the module, never edited by
# hand, and the worker bundle (build.sh one level up, dist/audioclass-worker.js)
# picks it up as an ordinary import.
#
# Needs only Go. -trimpath and no build ID make the output the same bytes on
# any machine with the same Go release.
#
# Usage:
#   ./build.sh            build and write both files
#   ./build.sh --check    build, and fail if the committed files are out of date

set -euo pipefail

cd "$(dirname "$0")"

CHECK=0
for arg in "$@"; do
    case "$arg" in
        --check) CHECK=1 ;;
        *) echo "unknown option: $arg" >&2; exit 2 ;;
    esac
done

command -v go >/dev/null || { echo "go not found" >&2; exit 1; }

WASM_OUT=../../audioclass/audioclass.wasm
LOADER_OUT=../../src/lib/audioClass/wasm_exec.js

GOROOT_DIR=$(go env GOROOT)
LOADER_SRC="$GOROOT_DIR/lib/wasm/wasm_exec.js"
[[ -f "$LOADER_SRC" ]] || LOADER_SRC="$GOROOT_DIR/misc/wasm/wasm_exec.js" # Go before 1.24
[[ -f "$LOADER_SRC" ]] || { echo "wasm_exec.js not found under $GOROOT_DIR" >&2; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

GOOS=js GOARCH=wasm go build -trimpath -buildvcs=false -ldflags='-s -w -buildid=' -o "$TMP/audioclass.wasm" .
{
    printf '// Generated by static/v2/native/audioclass/build.sh from %s (%s). Do not edit.\n' \
        "wasm_exec.js" "$(go env GOVERSION)"
    cat "$LOADER_SRC"
} > "$TMP/wasm_exec.js"

if [[ $CHECK == 1 ]]; then
    cmp -s "$TMP/audioclass.wasm" "$WASM_OUT" || { echo "$WASM_OUT is out of date — run $0" >&2; exit 1; }
    cmp -s "$TMP/wasm_exec.js" "$LOADER_OUT" || { echo "$LOADER_OUT is out of date — run $0" >&2; exit 1; }
    echo "audioclass.wasm and wasm_exec.js are up to date"
    exit 0
fi

mkdir -p "$(dirname "$WASM_OUT")" "$(dirname "$LOADER_OUT")"
install -m 644 "$TMP/audioclass.wasm" "$WASM_OUT"
cp "$TMP/wasm_exec.js" "$LOADER_OUT"
echo "wrote $WASM_OUT ($(numfmt --to=iec < <(wc -c < "$WASM_OUT"))) and $LOADER_OUT ($(go env GOVERSION))"

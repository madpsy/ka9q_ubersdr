// gen_labels.js -- build.sh's first step: the AudioSet class names, in model
// output order, from audioset_labels.csv (EfficientAT's
// metadata/class_labels_indices.csv: index,mid,display_name) into a C header.
//
//   node gen_labels.js audioset_labels.csv out.h

'use strict';

const fs = require('fs');

// RFC 4180: fields may be quoted, quotes doubled inside them.
function parseCSV(text) {
    const rows = [];
    let row = [], field = '', i = 0, quoted = false;
    while (i < text.length) {
        const c = text[i];
        if (quoted) {
            if (c === '"' && text[i + 1] === '"') { field += '"'; i += 2; continue; }
            if (c === '"') { quoted = false; i++; continue; }
            field += c; i++; continue;
        }
        if (c === '"') { quoted = true; i++; continue; }
        if (c === ',') { row.push(field); field = ''; i++; continue; }
        if (c === '\n' || c === '\r') {
            if (c === '\r' && text[i + 1] === '\n') i++;
            row.push(field); rows.push(row); row = []; field = ''; i++; continue;
        }
        field += c; i++;
    }
    if (field !== '' || row.length) { row.push(field); rows.push(row); }
    return rows;
}

function cString(s) {
    // UTF-8 bytes, escaped: the module hands them back as bytes for TextDecoder.
    let out = '"';
    for (const b of Buffer.from(s, 'utf8')) {
        if (b === 0x22) out += '\\"';
        else if (b === 0x5c) out += '\\\\';
        else if (b >= 0x20 && b < 0x7f) out += String.fromCharCode(b);
        else out += '\\' + b.toString(8).padStart(3, '0');
    }
    return out + '"';
}

function main() {
    const [csvPath, outPath] = process.argv.slice(2);
    const rows = parseCSV(fs.readFileSync(csvPath, 'utf8')).filter((r) => r.length >= 3);
    const labels = rows.slice(1).map((r) => r[2]);
    if (labels.length !== 527) throw new Error(`expected 527 labels, found ${labels.length}`);
    const lines = [
        '/* GENERATED by gen_labels.js from audioset_labels.csv. Do not edit. */',
        'static const char *const LABELS[527] = {',
        ...labels.map((l) => `    ${cString(l)},`),
        '};',
        'static const int LABEL_LEN[527] = {',
        ...labels.map((l) => `    ${Buffer.byteLength(l, 'utf8')},`),
        '};',
        '',
    ];
    fs.writeFileSync(outPath, lines.join('\n'));
}

main();

// embed.js — the last step of build.sh: strip the two modules and write them,
// base64-encoded, into the JS module the v2 bundle imports.
//
//   node embed.js <simd.raw.wasm> <scalar.raw.wasm> <out.js>
//
// Base64 inside a JS module rather than a .wasm file beside the bundle, because
// the v2 frontend is one esbuild bundle served from one place, and so is every
// copy of it -- the Electron and Capacitor apps stage the same dist/. A separate
// file would need a loader flag in build.sh, a route or MIME type on the server
// (instantiateStreaming insists on application/wasm) and the same again in each
// app. The cost is a third more bytes than the binary, ~30 kB here, and a
// decode on first use; neither matters next to the bundle.
//
// Custom sections are dropped. The linker's --strip-all already removes names
// and debug info, but it keeps "producers", which names the compiler version:
// harmless, and the only thing that would make two builds from the same code
// generator differ byte for byte.
//
// The generated file also records a hash of the sources it was built from, so
// test.js can tell a stale build from a current one without a toolchain.

'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function readLEB(buf, off) {
    let v = 0, shift = 0;
    for (;;) {
        const b = buf[off++];
        v += (b & 0x7f) * 2 ** shift;
        if (b < 0x80) return [v, off];
        shift += 7;
    }
}

function stripCustom(buf) {
    if (buf.readUInt32LE(0) !== 0x6d736100) throw new Error('not a wasm module');
    const parts = [buf.subarray(0, 8)];
    let off = 8;
    while (off < buf.length) {
        const start = off;
        const id = buf[off++];
        const [size, body] = readLEB(buf, off);
        off = body + size;
        if (id !== 0) parts.push(buf.subarray(start, off));
    }
    return Buffer.concat(parts);
}

// Must list every file whose content reaches the binaries or this output.
const SOURCES = ['pcmv4.h', 'api.c', 'iq.c', 'audio.c', 'rice.c', 'shim.c', 'build.sh', 'embed.js'];

function sourceHash(dir) {
    const h = crypto.createHash('sha256');
    for (const f of SOURCES) {
        h.update(f + '\0');
        h.update(fs.readFileSync(path.join(dir, f)));
        h.update('\0');
    }
    return h.digest('hex');
}

function main() {
    const [simdPath, scalarPath, outPath] = process.argv.slice(2);
    if (!outPath) {
        console.error('usage: node embed.js <simd.raw.wasm> <scalar.raw.wasm> <out.js>');
        process.exit(2);
    }
    const simd = stripCustom(fs.readFileSync(simdPath));
    const scalar = stripCustom(fs.readFileSync(scalarPath));
    fs.writeFileSync(path.join(path.dirname(simdPath), 'pcmv4-simd.wasm'), simd);
    fs.writeFileSync(path.join(path.dirname(scalarPath), 'pcmv4-scalar.wasm'), scalar);

    const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
    const abi = Number(/#define PV4_ABI_VERSION (\d+)/.exec(fs.readFileSync(path.join(__dirname, 'pcmv4.h'), 'utf8'))[1]);

    const js = `// GENERATED by static/v2/native/pcmv4/build.sh from the C sources beside it.
// Do not edit: change the sources and run that script. See its README.md.
//
// The two builds of the WebAssembly PCM v4 decoder, base64. pcm-v4-wasm.js is
// the only intended importer.

export const PCMV4_WASM_ABI = ${abi};

// sha256 of the sources (pcmv4/*.c, pcmv4.h, build.sh, embed.js) these were
// built from; test.js compares it against the tree to catch a stale build.
export const PCMV4_WASM_SOURCE_SHA256 = '${sourceHash(__dirname)}';

// ${simd.length} bytes, sha256 ${sha(simd)}
export const PCMV4_WASM_SIMD = '${simd.toString('base64')}';

// ${scalar.length} bytes, sha256 ${sha(scalar)}
export const PCMV4_WASM_SCALAR = '${scalar.toString('base64')}';
`;

    fs.writeFileSync(outPath, js);
    console.log(`simd ${simd.length} B, scalar ${scalar.length} B -> ${outPath}`);
}

if (require.main === module) main();

module.exports = { sourceHash, SOURCES };

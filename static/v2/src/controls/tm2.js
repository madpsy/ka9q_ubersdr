/**
 * One input report as `{ main, e1, e2, buttons }` — the three encoder
 * positions (u16) and the nine button bits (active low) — or null.
 *
 * Tmate2_C reads 9 bytes, the first a 1. If the device numbers its reports
 * that 1 is report ID 1 and WebHID has taken it off; if not, it is the first
 * byte of the data. Either reads the same here.
 */
export function parseInput(bytes, reportId = 0) {
    if (!bytes) return null;
    let off;
    if (reportId === 0) {
        if (bytes.length < INPUT_BYTES || bytes[0] !== 0x01) return null;
        off = 1;
    } else {
        if (bytes.length < INPUT_BYTES - 1) return null;
        off = 0;
    }
    const word = (i) => bytes[off + 2 * i] | (bytes[off + 2 * i + 1] << 8);
    return {
        main: word(WORD.main),
        e1: word(WORD.e1),
        e2: word(WORD.e2),
        buttons: (bytes[off + 6] | (bytes[off + 7] << 8)) & BUTTONS_IDLE,
    };
}

/** How far a 16-bit position moved, the short way round. */
export function encoderDelta(prev, now) {
    let d = (now - prev) & 0xFFFF;
    if (d >= 0x8000) d -= 0x10000;
    return d;
}

/** Whole steps out of `carry` counts at `per` counts a step, the rest carried; toward zero. */
export function takeSteps(carry, per = 1) {
    const steps = Math.trunc(carry / per) || 0;
    return { steps, carry: carry - steps * per };
}

export function tm2Available() {
    return typeof navigator !== 'undefined' && !!navigator.hid;
}

export function isTm2(device) {
    return !!device && device.vendorId === TM2_VENDOR_ID && device.productId === TM2_PRODUCT_ID;
}

// The output report's ID and length, from the descriptor when it declares one;
// otherwise what Tmate2_C writes — no ID, 43 bytes. A longer declared report is
// padded with zeros.
function outputReport(device) {
    for (const c of (device && device.collections) || []) {
        for (const r of c.outputReports || []) {
            let bits = 0;
            for (const i of r.items || []) bits += (i.reportSize || 0) * (i.reportCount || 0);
            return { id: r.reportId || 0, length: Math.max(OUTPUT_PAYLOAD, Math.ceil(bits / 8)) };
        }
    }
    return { id: 0, length: OUTPUT_PAYLOAD };
}

export class TM2Control extends Emitter {
    /** `clock`: now(), setTimeout(), clearTimeout() — the tests' seam. */
    constructor(clock = {}) {
        super();
        this.device = null;
        this.connected = false;
        this._now = clock.now || (() => Date.now());
        this._setTimeout = clock.setTimeout || ((fn, ms) => setTimeout(fn, ms));
        this._clearTimeout = clock.clearTimeout || ((id) => clearTimeout(id));
        this._onReport = (e) => this._report(e);
        this._onGone = (e) => { if (e.device === this.device) this._lost(); };
        // Closing the tab blanks the console, as Disconnect does, so it is not
        // left showing a receiver nothing is driving. Best effort: the browser
        // may close the device before the write lands, and there is no waiting.
        this._onPageHide = () => { if (this.connected) this._sendFrame(newFrame()); };
        this._rx = null;
        this._settings = tm2Settings(null);
        this._pages = { e1: 0, e2: 0 };
        this._popup = null;      // { kind, until }
        this._popupTimer = null;
        this._click = 0;
        this._reset();
    }

    _reset() {
        this._lastRaw = null;
        this._pos = null;        // { main, e1, e2 } last positions
        this._counts = { main: 0, e1: 0, e2: 0 };
        this._flushTimer = null;
        this._buttons = BUTTONS_IDLE;
        this._down = {};
        this._held = {};
        this._timers = {};
        this._heard = false;
        this._answerTimer = null;
        this._sent = null;
        this._sentAt = 0;
        this._want = null;
        this._writing = false;
        this._pumping = null;
        this._closing = false;
        this._writeFailed = false;
    }

    /** Which page each small knob is on, by name — for the panel and the tests. */
    get pages() {
        return { e1: E1_PAGES[this._pages.e1], e2: E2_PAGES[this._pages.e2] };
    }

    // Must be called from a user gesture — the device chooser is gated on one.
    async connect() {
        if (!tm2Available()) {
            this.emit('message', { text: 'This browser has no WebHID API — try Chrome or Edge.', tone: 'error' });
            return false;
        }
        let devices;
        try {
            devices = await navigator.hid.requestDevice({
                filters: [{ vendorId: TM2_VENDOR_ID, productId: TM2_PRODUCT_ID }],
            });
        } catch (err) {
            this.emit('message', { text: `Could not open the TM-2: ${err.message}`, tone: 'error' });
            return false;
        }
        const device = (devices || []).find(isTm2);
        if (!device) return false;
        return this._start(device, false);
    }

    // A TM-2 this origin was already granted, with no chooser and no gesture.
    async autoConnect() {
        if (!tm2Available() || this.connected) return false;
        let devices;
        try {
            devices = await navigator.hid.getDevices();
        } catch (err) {
            return false;
        }
        const device = (devices || []).find(isTm2);
        if (!device) return false;
        return this._start(device, true);
    }

    async _start(device, quiet) {
        try {
            if (!device.opened) await device.open();
        } catch (err) {
            if (!quiet) {
                this.emit('message', {
                    text: `Could not open the TM-2: ${err.message}. On Linux it needs a udev rule — see the desktop client's README.`,
                    tone: 'error',
                });
            }
            return false;
        }
        this.device = device;
        const out = outputReport(device);
        this._outId = out.id;
        this._outLength = out.length;
        this._reset();
        this._click = 0;
        this.connected = true;
        device.addEventListener('inputreport', this._onReport);
        if (navigator.hid.addEventListener) navigator.hid.addEventListener('disconnect', this._onGone);
        if (typeof window !== 'undefined' && window.addEventListener) window.addEventListener('pagehide', this._onPageHide);
        this.emit('state', { connected: true });
        this.emit('message', { text: 'TM-2 connected', tone: 'good' });
        this._answerTimer = this._setTimeout(() => {
            this._answerTimer = null;
            if (this._heard || !this.connected) return;
            this.emit('message', {
                text: 'The TM-2 is open but sends nothing. Close ELAD’s software or anything else using it, then unplug and replug it.',
                tone: 'warn',
            });
        }, ANSWER_MS);
        this._render();
        return true;
    }

    // The LCD, LEDs and backlight go dark first: a console left showing a
    // frequency after the page has let go of it says it is still in charge.
    // As close_tmate2(): the click bit cleared and the frame sent twice, which
    // Tmate2_C found the unit needs before the click is reset.
    async disconnect() {
        const device = this.device;
        if (!device) return;
        // Deaf first: a knob turned while the blank frames go out must not arm
        // a timer that fires into the receiver after this has let go.
        device.removeEventListener('inputreport', this._onReport);
        this._clearTimers();
        // Let a write that is already out finish, and start no more.
        this._closing = true;
        if (this._pumping) await this._pumping;
        const blank = newFrame();
        await this._sendFrame(blank);
        await this._sendFrame(blank);
        this._detach();
        try { await device.close(); } catch (e) { /* already gone */ }
        this.emit('state', { connected: false });
        this.emit('message', { text: 'Disconnected', tone: 'info' });
    }

    _lost() {
        this._clearTimers();
        this._detach();
        this.emit('state', { connected: false });
        this.emit('message', { text: 'TM-2 disconnected', tone: 'warn' });
    }

    _detach() {
        if (this.device) this.device.removeEventListener('inputreport', this._onReport);
        if (tm2Available() && navigator.hid.removeEventListener) {
            navigator.hid.removeEventListener('disconnect', this._onGone);
        }
        if (typeof window !== 'undefined' && window.removeEventListener) window.removeEventListener('pagehide', this._onPageHide);
        this.device = null;
        this.connected = false;
    }

    _clearTimers() {
        for (const id of Object.values(this._timers)) this._clearTimeout(id);
        this._timers = {};
        for (const t of ['_flushTimer', '_answerTimer', '_popupTimer']) {
            if (this[t] !== null) this._clearTimeout(this[t]);
            this[t] = null;
        }
    }

    // --- input -------------------------------------------------------------

    _report(e) {
        const view = e.data;
        const bytes = new Uint8Array(view.buffer, view.byteOffset, view.byteLength);
        this._heard = true;
        if (this._answerTimer !== null) {
            this._clearTimeout(this._answerTimer);
            this._answerTimer = null;
        }
        // It reports continuously; most reports are the last one again.
        const raw = bytes.join(',');
        if (raw === this._lastRaw) return;
        this._lastRaw = raw;
        const r = parseInput(bytes, e.reportId);
        if (!r) return;

        if (this._pos === null) {
            // The first report is where the knobs are, not a movement — and a
            // button already held is not a press.
            this._pos = { main: r.main, e1: r.e1, e2: r.e2 };
            this._buttons = r.buttons;
            return;
        }
        let moved = false;
        for (const knob of ['main', 'e1', 'e2']) {
            const d = encoderDelta(this._pos[knob], r[knob]);
            if (!d) continue;
            this._pos[knob] = r[knob];
            // Clockwise positive. The main encoder counts the other way
            // (Tmate2_C's readme, and its main.c subtracts it).
            this._counts[knob] += knob === 'main' ? -d : d;
            moved = true;
        }
        if (moved && this._flushTimer === null) {
            this._flushTimer = this._setTimeout(() => this._flush(), FLUSH_MS);
        }
        if (r.buttons !== this._buttons) {
            const was = this._buttons;
            this._buttons = r.buttons;
            this._buttonsChanged(was, r.buttons);
        }
    }

    _flush() {
        this._flushTimer = null;
        for (const knob of ['main', 'e1', 'e2']) {
            const per = knob === 'main' ? MAIN_COUNTS_PER_STEP : E_COUNTS_PER_DETENT;
            const { steps, carry } = takeSteps(this._counts[knob], per);
            this._counts[knob] = carry;
            if (!steps) continue;
            const dir = steps > 0 ? 'up' : 'down';
            if (knob === 'main') {
                // Summed: the tuning functions move by the count they are
                // given, and the acceleration can make it dozens a flush.
                this.emit('input', { key: `main_${dir}`, event: { kind: 'relative', delta: steps } });
                continue;
            }
            // A detent at a time. Several functions a small knob is mapped to
            // take a fixed step per event whatever its count — "Volume up",
            // "Filter wider" — so three quick clicks summed into one event
            // would move them once. Detented knobs turn slowly enough for this.
            const key = `${knob}_${this.pages[knob]}_${dir}`;
            const one = Math.sign(steps);
            for (let i = 0; i < Math.abs(steps); i += 1) {
                this.emit('input', { key, event: { kind: 'relative', delta: one } });
            }
            // Turning a small knob shows what it is setting, live.
            this._showPopup(this.pages[knob]);
        }
    }

    _buttonsChanged(was, now) {
        for (const { bit, name } of BUTTONS) {
            const wasDown = (was & (1 << bit)) === 0;
            const isDown = (now & (1 << bit)) === 0;
            if (!wasDown && isDown) this._press(name);
            else if (wasDown && !isDown) this._release(name);
        }
    }

    _press(name) {
        this._down[name] = this._now();
        this._timers[name] = this._setTimeout(() => {
            delete this._timers[name];
            this._held[name] = true;
            if (this._settings.clickOnHold) this.click();
        }, HOLD_MS);
    }

    _release(name) {
        const since = this._down[name];
        delete this._down[name];
        if (this._timers[name] !== undefined) {
            this._clearTimeout(this._timers[name]);
            delete this._timers[name];
        }
        delete this._held[name];
        if (since === undefined) return;
        // Measured, not taken from the timer: a busy page that runs the timer
        // late must still call a 700 ms press a hold.
        const hold = this._now() - since >= HOLD_MS;
        if (!hold && (name === 'e1' || name === 'e2')) {
            this._nextPage(name);
            return;
        }
        this.emit('input', { key: `${name}_${hold ? 'hold' : 'tap'}`, event: { kind: 'trigger' } });
    }

    _nextPage(knob) {
        const pages = PAGES[knob];
        this._pages[knob] = (this._pages[knob] + 1) % pages.length;
        this.emit('page', this.pages);
        this._showPopup(this.pages[knob]);
    }

    // --- output ------------------------------------------------------------

    /** The receiver as it is now — see renderTm2 for the fields. */
    setReceiver(rx) {
        const kind = changePopup(this._rx, rx);
        this._rx = rx ? { ...rx } : null;
        if (kind) this._showPopup(kind);
        else this._render();
    }

    setSettings(raw) {
        this._settings = tm2Settings(raw);
        this._render();
    }

    /** The TM-2's click: it sounds when the click bit changes. */
    click() {
        this._click ^= 1;
        this._render();
    }

    _showPopup(kind) {
        this._popup = { kind, until: this._now() + POPUP_MS };
        if (this._popupTimer !== null) this._clearTimeout(this._popupTimer);
        this._popupTimer = this._setTimeout(() => {
            this._popupTimer = null;
            this._render();
        }, POPUP_MS);
        this._render();
    }

    /** The frame this moment calls for, click bit included. */
    frame() {
        const now = this._now();
        if (this._popup && now >= this._popup.until) this._popup = null;
        const ui = {
            ...this.pages,
            popup: this._popup ? this._popup.kind : null,
            blinkOn: Math.floor(now / BLINK_MS) % 2 === 0,
        };
        const f = renderTm2({ rx: this._rx, settings: this._settings, ui });
        setField(f, 'click', this._click);
        return f;
    }

    _render() {
        if (!this.connected) return;
        this._want = this.frame();
        if (this._now() - this._sentAt >= REFRESH_MS) this._sent = null;
        this._pump();
    }

    // One write at a time, and only the newest frame: a burst of changes while
    // a write is out collapses into one.
    _pump() {
        if (this._writing) return this._pumping;
        this._writing = true;
        const run = this._pumpLoop();
        // The loop can finish before the first await, and has then already
        // cleared these; only a write still out is worth waiting for.
        if (this._writing) this._pumping = run;
        return run;
    }

    async _pumpLoop() {
        try {
            while (this.connected && !this._closing && this._want && !framesEqual(this._want, this._sent)) {
                const f = this._want;
                // eslint-disable-next-line no-await-in-loop
                const ok = await this._sendFrame(f);
                if (!ok) break;
                this._sent = f;
                this._sentAt = this._now();
            }
        } finally {
            this._writing = false;
            this._pumping = null;
        }
    }

    async _sendFrame(frame) {
        const device = this.device;
        if (!device || !device.sendReport) return false;
        try {
            await device.sendReport(this._outId || 0, tm2Payload(frame, this._outLength));
            // Said again if it fails again after this: one failure a
            // connection hides a second, different one.
            this._writeFailed = false;
            return true;
        } catch (err) {
            if (!this._writeFailed && device === this.device) {
                this._writeFailed = true;
                this.emit('message', { text: `Could not write to the TM-2: ${err.message}`, tone: 'warn' });
            }
            return false;
        }
    }
}

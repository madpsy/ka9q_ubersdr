// ELAD TM-2 (formerly the Woodbox Radio TMate 2) — a USB tuning console with a
// big main knob, two small push knobs (E1, E2), six function keys, two LEDs and
// a segment LCD with an RGB backlight. Read and written over WebHID.
//
// Two-way like the UberSDR Dial: the knobs and keys drive the receiver through
// the mapping table like any surface, and the LCD shows the receiver back —
// frequency, mode, S-meter, step, what each small knob is adjusting. What it
// shows is tm2display.js; how a frame is laid out is tm2frame.js.
//
// Protocol: github.com/microenh/Tmate2_C, which drives a real unit with hidapi
// (ELAD's SDK is Windows-only and on request). test/tm2.tmate2c.json holds
// reports and frames generated by that code, and the tests hold this driver to
// them. In brief:
//
//   Input, 9 bytes, sent continuously: [0x01] then little-endian
//     u16 main encoder   a position, not a delta — counts up anticlockwise
//     u16 E2 encoder     counts up clockwise
//     u16 E1 encoder     counts up clockwise
//     9 bits of buttons, active low: F1..F6, main push, E2 push, E1 push
//   Output, 43 bytes (report ID 0): every segment, the LEDs, the backlight,
//     the contrast and the main encoder's acceleration — tm2frame.js.
//
// Behaviour follows ELAD's (TM-2 User Manual, Rev 2, 05/2021): the main knob
// tunes and its push is the tuning lock (the red TUNE LOCK LED), each small
// knob's push steps through what that knob adjusts, and the LCD labels it.
// A small knob's tap is that page step and nothing else; its hold, the main
// push and every key are mapped like any other surface's buttons.
//
// The buttons report only down and up, so tap and hold are told apart here at
// the RC-28's 600 ms, the hold firing on release; the TM-2 clicks the moment a
// press becomes a hold, which is the only way to feel that moment.
//
// Wherever this rests on something not yet checked against a unit it says
// "TM-2 UNVERIFIED", so a search finds every assumption.

import { Emitter } from '../radio/emitter.js';
import { framesEqual, newFrame, tm2Payload, setField, OUTPUT_PAYLOAD } from './tm2frame.js';
import {
    E1_PAGES, E2_PAGES, PAGE_LABEL, changePopup, renderTm2, tm2Settings,
} from './tm2display.js';

// Tmate2_C's VENDOR_ID / PRODUCT_ID, and its 50-TMATE2.rules.
export const TM2_VENDOR_ID = 0x1721;
export const TM2_PRODUCT_ID = 0x0614;

export const HOLD_MS = 600;
// Encoder movement is gathered and sent at this pace, summed rather than
// thinned, as the RC-28's is: the TM-2 reports many times a second.
export const FLUSH_MS = 50;
// It reports continuously, so silence this long after opening means something
// else has it (ELAD's own software, say) or it is not the device it seems.
export const ANSWER_MS = 2000;
// How long a popup holds the main display before the frequency comes back.
export const POPUP_MS = 1500;
export const BLINK_MS = 500;
// TM-2 UNVERIFIED: whether the unit needs to hear from the host to keep its
// display. Tmate2_C writes after every read; this sends only changes, plus the
// whole frame again at least this often, which is cheap and covers a device
// that has reset itself.
export const REFRESH_MS = 1000;

// TM-2 UNVERIFIED: counts per step. The small knobs are detented ("two detent
// encoders", the manual) and are taken as one count a detent; the main knob as
// one count a step at its slowest speed, the acceleration (tm2display.js)
// multiplying from there. Either would be a constant to change here.
export const MAIN_COUNTS_PER_STEP = 1;
export const E_COUNTS_PER_DETENT = 1;

const INPUT_BYTES = 9;

// TM-2 UNVERIFIED: which input word is which knob. Tmate2_C's code reads the
// second word as E2 and the third as E1 (bitfields.h), and its readme says the
// opposite; the code is what ran against a unit, so it is followed. On the
// panel E1 is the left of the two small knobs and E2 the middle one.
const WORD = { main: 0, e2: 1, e1: 2 };

// Button bits, as bitfields.h has them (readme disagrees on E1/E2 — as above).
const BUTTONS = [
    { bit: 0, name: 'f1' },
    { bit: 1, name: 'f2' },
    { bit: 2, name: 'f3' },
    { bit: 3, name: 'f4' },
    { bit: 4, name: 'f5' },
    { bit: 5, name: 'f6' },
    { bit: 6, name: 'main' },
    { bit: 7, name: 'e2' },
    { bit: 8, name: 'e1' },
];
const BUTTONS_IDLE = 0x1FF;

const PAGES = { e1: E1_PAGES, e2: E2_PAGES };

export const TM2_KEYS = [
    { key: 'main_up', label: 'Main knob — clockwise' },
    { key: 'main_down', label: 'Main knob — anticlockwise' },
    { key: 'main_tap', label: 'Main knob push — tap' },
    { key: 'main_hold', label: 'Main knob push — hold' },
    ...['e1', 'e2'].flatMap((knob) => [
        ...PAGES[knob].flatMap((page) => [
            { key: `${knob}_${page}_up`, label: `${knob.toUpperCase()} (${PAGE_LABEL[page]}) — clockwise` },
            { key: `${knob}_${page}_down`, label: `${knob.toUpperCase()} (${PAGE_LABEL[page]}) — anticlockwise` },
        ]),
        { key: `${knob}_hold`, label: `${knob.toUpperCase()} push — hold` },
    ]),
    ...[1, 2, 3, 4, 5, 6].flatMap((n) => [
        { key: `f${n}_tap`, label: `F${n} — tap` },
        { key: `f${n}_hold`, label: `F${n} — hold` },
    ]),
];

const KEY_LABEL = Object.fromEntries(TM2_KEYS.map((k) => [k.key, k.label]));

export function tm2KeyLabel(key) {
    return KEY_LABEL[key] || key;
}

